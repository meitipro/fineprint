def page_contract(tree: ast.Module) -> str:
    rows = methods(tree)
    refs = refusals(tree)
    out = [front("Contract reference", "All ten methods of the Fineprint contract, generated from the source."), HEADER]
    out.append(
        "One contract, ten methods. Seven write, three read. Money moves only in `withdraw`: `challenge` and `post_summary` take it in, "
        "and `judge`, `retract` and `close_summary` only move balances inside the contract.\n\n"
    )
    out.append("| Method | Kind | What it does |\n|---|---|---|\n")
    for m in rows:
        kind = {"write": "write", "payable": "write, payable", "view": "view"}[m["kind"]]
        summary = mdx_text(m["doc"].split(". ")[0].rstrip(".") + ".")
        out.append(f"| [`{m['name']}`](#{m['name'].replace('_', '-')}) | {kind} | {summary} |\n")
    out.append("\n")
    for m in rows:
        out.append(f"## {m['name']}\n\n")
        out.append(fence("python", m["signature"]))
        out.append(f"\n{mdx_text(m['doc'])}\n\n")
        mine = [r for r in refs if m["name"] in r["where"] and r["prefix"] == "E"]
        if mine:
            out.append("Refuses with:\n\n")
            for r in mine:
                out.append(f"- {mdx_text(r['text'])}\n")
            out.append("\n")
    out.append(
        f"The source is [`contracts/fineprint.py`]({REPO}/contracts/fineprint.py). `get_doc` takes a document id (64 hex characters), "
        "the number of a document in the order registered, an account address (its balance, summaries and challenges), or an empty string "
        "(the totals). Every view answers `{\"found\": false}` for an unknown id instead of raising, and always carries `totals`.\n"
    )
    return "".join(out)


def page_errors(tree: ast.Module) -> str:
    refs = refusals(tree)
    out = [front("Errors", "Every sentence the contract refuses with, generated from the source."), HEADER]
    out.append(
        "A refusal is a deterministic `UserError` whose sentence starts with `[EXPECTED]`. Validators agree on it byte for byte, so the transaction is "
        "**ACCEPTED** with an execution error. The site and the scripts treat that as a refusal, never as success: success is an accepted status "
        "**and** a leader execution that returned.\n\n"
    )
    out.append(
        "A model answer that cannot be read is `[LLM_ERROR]`. It always disagrees, so the round rotates to a committee that can answer; "
        "nothing is settled by it.\n\n"
    )
    out.append("| Sentence | From |\n|---|---|\n")
    for r in refs:
        if r["prefix"] == "E":
            where = ", ".join(f"`{w}`" for w in r["where"] if not w.startswith("_")) or ", ".join(f"`{w}`" for w in r["where"])
            out.append(f"| {mdx_text(r['text'])} | {where} |\n")
    out.append("\n## Unreadable model answers\n\n| Sentence | From |\n|---|---|\n")
    for r in refs:
        if r["prefix"] == "L":
            out.append(f"| `[LLM_ERROR]` {mdx_text(r['text'])} | {', '.join(f'`{w}`' for w in r['where'])} |\n")
    return "".join(out)


def page_hashing(tree: ast.Module) -> str:
    vectors = json.loads((ROOT / "tests" / "vectors.json").read_text(encoding="utf-8"))["vectors"]
    out = [front("Hashing", "How a document id is computed, with test vectors the contract and the browser both pass."), HEADER]
    out.append(
        "A document id is the sha256 of its text, so a summary always points at text that cannot change under it. "
        "The contract and the browser compute the same bytes, and both are held to the vectors below.\n\n"
    )
    out.append("## The bytes\n\n")
    out.append(
        "The digest runs over the UTF-8 bytes of `fineprint-doc-v1` and a newline, then, for the title and each clause in order, "
        "the byte length of the text in UTF-8, a colon, the text, and a newline. The length prefix matters: with only a newline between texts, "
        "a line break inside a clause could move a boundary and make two different documents one (found by `scripts/mutate.py`).\n\n"
    )
    out.append("The texts are normalised first, because that is what the contract stores: line endings become `\\n` and the whitespace Python's `str.strip()` removes is taken off both ends of the title and of each clause.\n\n")
    out.append(fence("python", ast.get_source_segment(CONTRACT.read_text(encoding="utf-8"), next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "doc_hash")) or "", "contracts/fineprint.py"))
    out.append("\nThe same in JavaScript, which is the code the site runs:\n\n")
    out.append(fence("js", (EXAMPLES / "hash-a-document.mjs").read_text(encoding="utf-8").split("*/", 1)[1], "web/examples/hash-a-document.mjs"))
    out.append("\n## Test vectors\n\n")
    out.append("Written by `scripts/gen_vectors.py` from the contract's own function. `node web/scripts/hash-parity.mjs` and the test suite check the browser code against them.\n\n")
    out.append("| Case | Title | Clauses | Id |\n|---|---|---|---|\n")
    for v in vectors:
        title = v["normalised_title"].replace("|", "/")
        shown = title if len(title) <= 28 else title[:27] + "…"
        out.append(f"| {mdx_text(v['name'])} | {mdx_text(shown)} | {len(v['normalised_clauses'])} | `{v['id']}` |\n")
    out.append(f"\nThe full inputs, including the raw text a person might paste, are in [`tests/vectors.json`]({REPO}/tests/vectors.json).\n")
    return "".join(out)


