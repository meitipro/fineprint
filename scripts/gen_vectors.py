#!/usr/bin/env python3
"""
Write tests/vectors.json: document ids produced by the contract's own code.

    python scripts/gen_vectors.py           # write it
    python scripts/gen_vectors.py --check   # exit 1 when the file is not what the contract produces

A document id is sha256 over length-prefixed UTF-8 bytes of the normalised
title and clauses (see doc_hash in contracts/fineprint.py). The site computes
the same bytes in the browser, and web/scripts/hash-parity.mjs holds its answer
to this file. Each vector carries the RAW input as a person might paste it
(Windows line endings, no-break spaces at the edges, Persian digits, emoji) and
the normalised text and id the contract stores.
"""

from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tests"))

from harness import load  # noqa: E402
import genvm_double as D  # noqa: E402

OUT = ROOT / "tests" / "vectors.json"

CASES = [
    ("plain", "Kiln airdrop terms", ["Hold 100 KILN at the Oct 1 snapshot.", "Wallets created later are not eligible.", "Claims close on Dec 15."]),
    (
        "the build spec document",
        "Kiln airdrop terms",
        [
            "Hold at least 100 KILN at the Oct 1 snapshot. Wallets created after the snapshot are not eligible.",
            "Each eligible wallet receives a share of the pool in proportion to its balance at the snapshot.",
            "The claim opens on Oct 15 and closes on Dec 15. Unclaimed tokens return to the treasury.",
            "Claimed tokens vest linearly over 12 months, with 25% available at the time of claim. Unvested tokens cannot be transferred.",
            "Claiming requires a wallet that has passed the verification step described in the claim portal.",
            "Kiln may change or end the program at any time without notice.",
        ],
    ),
    ("windows line endings", "Quill grants", ["Line one.\r\nLine two.", "Old Mac\rline endings.", "Unix\nline endings."]),
    ("surrounding whitespace", "  Padded title \n", ["  leading", "trailing  \t", "\n\nboth\n\n"]),
    ("no-break and ideographic spaces at the edges", " Pellmark sale　", [" nbsp ", "　wide　", " em space "]),
    ("control whitespace python strips", "Edges", ["\x1c\x1d\x1e\x1fseparators\x1f", "\x85next line\x85", "\x0bvertical tab\x0c"]),
    ("persian", "شرایط ایردراپ", ["باید ۱۰۰ توکن در لحظهٔ اسنپ‌شات داشته باشید.", "کیف‌پول‌های ساخته‌شده بعد از آن واجد شرایط نیستند.", "زمان ادعا ۳۰ روز است."]),
    ("spanish with accents", "Términos del programa", ["Mantén 100 KILN en la instantánea.", "No se admiten billeteras nuevas.", "El plazo termina el 15 de diciembre."]),
    ("emoji and astral characters", "Launch \U0001f680", ["\U0001f525 fire and \U0001d54f math", "Á combining mark", "Zero​width space inside"]),
    ("a boundary between texts", "ab", ["c", "d", "e"]),
    ("the same letters, a different boundary", "a", ["bc", "d", "e"]),
    ("inner blank lines and indentation", "Layout", ["Para one.\n\n  Indented para two.\n\tTabbed three.", "b", "c"]),
    ("the limits", "t" * 80, ["x" * 500, "y" * 500, "z"]),
    ("twelve clauses", "Twelve", ["clause %d" % n for n in range(1, 13)]),
]


def build() -> dict:
    gl = D.GL()
    mod = load(gl)
    vectors = []
    for name, title, clauses in CASES:
        clean_title = mod._line(title, "the title", mod.MAX_TITLE)
        clean_clauses = [mod._block(c, "a clause", mod.MAX_CLAUSE) for c in clauses]
        vectors.append(
            {
                "name": name,
                "title": title,
                "clauses": clauses,
                "normalised_title": clean_title,
                "normalised_clauses": clean_clauses,
                "id": mod.doc_hash(clean_title, clean_clauses),
            }
        )
    return {
        "about": "Document ids as the contract computes them. See doc_hash in contracts/fineprint.py. Generated by scripts/gen_vectors.py.",
        "hash": "sha256 over 'fineprint-doc-v1\\n' then, for the title and each clause, <UTF-8 byte length>:<text>\\n",
        "vectors": vectors,
    }


def main() -> int:
    text = json.dumps(build(), indent=2, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("tests/vectors.json is not what the contract produces. Run: python scripts/gen_vectors.py")
            return 1
        print("tests/vectors.json matches the contract")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()} ({len(json.loads(text)['vectors'])} vectors)")
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    raise SystemExit(main())
