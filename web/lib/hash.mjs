// The id of a document, byte for byte what contracts/fineprint.py computes.
//
//   sha256 over the UTF-8 bytes of
//     "fineprint-doc-v1\n"
//     then, for the title and each clause in order,
//     <byte length of the text in UTF-8> ":" <text> "\n"
//
// over the NORMALISED texts: line endings as \n and the whitespace Python's
// str.strip() removes taken off both ends. A pure JavaScript SHA-256 keeps the
// browser, the server and the tests on one implementation, with no dependency
// on crypto.subtle (which needs a secure context and is asynchronous).
// scripts/hash-parity.mjs holds this file to tests/vectors.json.

export const HASH_VERSION = "fineprint-doc-v1";

// Exactly the code points for which Python's str.isspace() is true.
const SPACE =
  "\\t\\n\\u000b\\u000c\\r\\u001c-\\u001f \\u0085\\u00a0\\u1680\\u2000-\\u200a\\u2028\\u2029\\u202f\\u205f\\u3000";
const EDGES = new RegExp("^[" + SPACE + "]+|[" + SPACE + "]+$", "g");

/** Python's str.strip(). */
export function strip(text) {
  return String(text ?? "").replace(EDGES, "");
}

/** A single-line text as the contract stores it (the title, a claim). */
export function normaliseLine(text) {
  return strip(text);
}

/** A text that may run over several lines (a clause). */
export function normaliseBlock(text) {
  return strip(String(text ?? "").replace(/\r\n/g, "\n").replace(/\r/g, "\n"));
}

/** Length in characters as Python counts them: code points, not UTF-16 units. */
export function length(text) {
  let n = 0;
  for (const _ of String(text)) n++; // eslint-disable-line no-unused-vars
  return n;
}

